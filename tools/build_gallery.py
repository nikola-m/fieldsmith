"""Run every example and write docs/gallery.md with the real output."""
import glob, os, subprocess, sys, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ["# Example gallery\n", "Generated by `tools/build_gallery.py`; output is the real output of each script.\n"]
for path in sorted(glob.glob(os.path.join(root, "examples", "[0-9]*.py"))):
    src = open(path).read()
    title = re.match(r'"""(.*?)\n', src).group(1)
    r = subprocess.run([sys.executable, path], capture_output=True, text=True, cwd=root)
    out += [f"## {title}\n", f"Source: [`examples/{os.path.basename(path)}`](../examples/{os.path.basename(path)})\n",
            "```text", (r.stdout + r.stderr).strip(), "```\n"]
open(os.path.join(root, "docs", "gallery.md"), "w").write("\n".join(out))
